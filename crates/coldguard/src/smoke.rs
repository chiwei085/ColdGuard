//! End-to-end checks with temporary brokers and emulators.

use crate::{cosim::Clock, toolchain::Toolchain};
use serde_json::Value;
use std::{
    fs,
    io::Read,
    net::{Ipv4Addr, TcpListener, TcpStream},
    path::Path,
    process::{Child, Command, Stdio},
    sync::{Arc, Mutex},
    thread::{sleep, spawn},
    time::{Duration, Instant, SystemTime},
};

type Result<T = ()> = std::result::Result<T, String>;

const BOOT_MARKER: &str = "COLDGUARD_BOOT_OK";
const MQTT_MARKER: &str = "COLDGUARD_MQTT_OK";
const QUANTUM_NS: u64 = 1_000_000;
// Pin the subnet used by the firmware.
const NET: &str = "user,net=192.168.4.0/24";

struct KillOnDrop(Child);

impl Drop for KillOnDrop {
    fn drop(&mut self) {
        // timeout forwards SIGTERM to the child. SIGKILL would orphan it.
        let _ = Command::new("/usr/bin/kill")
            .arg(self.0.id().to_string())
            .status();
        let _ = self.0.wait();
    }
}

fn free_port() -> Result<u16> {
    TcpListener::bind((Ipv4Addr::LOCALHOST, 0))
        .and_then(|l| l.local_addr())
        .map(|a| a.port())
        .map_err(|e| e.to_string())
}

fn broker(t: &Toolchain) -> Result<(KillOnDrop, u16)> {
    let program = t.which("mosquitto").ok_or("mosquitto not found")?;
    let port = free_port()?;
    let mut child = KillOnDrop(
        t.command(&program)
            .args(["-p", &port.to_string()])
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .spawn()
            .map_err(|e| e.to_string())?,
    );
    for _ in 0..50 {
        if TcpStream::connect((Ipv4Addr::LOCALHOST, port)).is_ok() {
            return Ok((child, port));
        }
        if let Ok(Some(s)) = child.0.try_wait() {
            return Err(format!("mosquitto failed to start ({s})"));
        }
        sleep(Duration::from_millis(100));
    }
    Err("mosquitto did not accept connections within 5 seconds".into())
}

/// Test retained messages with a temporary broker.
pub fn mqtt_roundtrip(t: &Toolchain) -> Result {
    let need = |n: &str| t.which(n).ok_or(format!("{n} not found"));
    let (publ, subs) = (need("mosquitto_pub")?, need("mosquitto_sub")?);
    let (_broker, port) = broker(t)?;
    let p = port.to_string();
    let base = ["-h", "127.0.0.1", "-p", &p, "-t", "coldguard/doctor"];
    t.output(
        publ,
        &[&base[..], &["-r", "-q", "1", "-m", "ping"]].concat(),
    )?;
    let got = t.output(subs, &[&base[..], &["-C", "1", "-W", "5"]].concat())?;
    if got == "ping" {
        Ok(())
    } else {
        Err(format!("Unexpected payload received: {got}"))
    }
}

/// Require a smoke image from the pinned IDF and current sources.
pub fn check_build(t: &Toolchain) -> Result {
    let build = t.smoke_build();
    let text = fs::read_to_string(build.join("project_description.json"))
        .map_err(|_| "Smoke firmware has not been built".to_string())?;
    let json: Value = serde_json::from_str(&text).map_err(|e| e.to_string())?;
    if json["git_revision"] != t.m.esp_idf.version.as_str() || json["target"] != "esp32s3" {
        return Err(format!(
            "Built with {} for {}",
            json["git_revision"], json["target"]
        ));
    }
    let image = modified(&t.smoke_image())?;
    if newest(&t.smoke_source())? > image {
        return Err("Smoke firmware is older than its sources".into());
    }
    Ok(())
}

fn modified(path: &Path) -> Result<SystemTime> {
    fs::metadata(path)
        .and_then(|m| m.modified())
        .map_err(|e| format!("{}: {e}", path.display()))
}

/// Find the newest source. Skip files generated by the build.
fn newest(dir: &Path) -> Result<SystemTime> {
    let mut newest = SystemTime::UNIX_EPOCH;
    for entry in fs::read_dir(dir).map_err(|e| e.to_string())? {
        let path = entry.map_err(|e| e.to_string())?.path();
        let name = path.file_name().unwrap_or_default();
        if name == "managed_components" || name == "dependencies.lock" || name == "build" {
            continue;
        }
        let time = if path.is_dir() {
            self::newest(&path)?
        } else {
            modified(&path)?
        };
        newest = newest.max(time);
    }
    Ok(newest)
}

struct Emulator {
    _child: KillOnDrop,
    output: Arc<Mutex<Vec<u8>>>,
}

impl Emulator {
    fn start(t: &Toolchain, args: &[&str]) -> Result<Self> {
        let (bin, image) = (t.esp_emu(), t.smoke_image());
        for path in [&bin, &image] {
            if !path.is_file() {
                return Err(format!("{} does not exist", path.display()));
            }
        }
        let mut child = t
            .command(&bin)
            .args(["--chip", "esp32s3", "--net", NET, "--firmware"])
            .arg(&image)
            .args(args)
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .map_err(|e| e.to_string())?;
        let output = Arc::new(Mutex::new(vec![]));
        // Drain both pipes so the emulator never blocks.
        if let Some(pipe) = child.stdout.take() {
            collect(pipe, output.clone());
        }
        if let Some(pipe) = child.stderr.take() {
            collect(pipe, output.clone());
        }
        Ok(Self {
            _child: KillOnDrop(child),
            output,
        })
    }

    fn text(&self) -> String {
        String::from_utf8_lossy(&self.output.lock().unwrap()).into_owned()
    }

    fn wait_for(&self, marker: &str, limit: Duration) -> Result {
        let end = Instant::now() + limit;
        while Instant::now() < end {
            if self.text().contains(marker) {
                return Ok(());
            }
            sleep(Duration::from_millis(20));
        }
        Err(self.missing(marker))
    }

    fn missing(&self, marker: &str) -> String {
        let text = self.text();
        let last = text.trim().lines().last().unwrap_or("no output");
        format!("{marker} not found. Last output: {last}")
    }
}

fn collect(mut pipe: impl Read + Send + 'static, output: Arc<Mutex<Vec<u8>>>) {
    spawn(move || {
        let mut buf = [0; 4096];
        while let Ok(n @ 1..) = pipe.read(&mut buf) {
            output.lock().unwrap().extend(&buf[..n]);
        }
    });
}

pub struct Boot {
    pub boot: Result<String>,
    pub cosim: Result<String>,
    pub speed: Result<f64>,
}

/// Boot offline under a held clock, then measure lockstep speed.
pub fn boot(t: &Toolchain) -> Boot {
    let started = free_port().and_then(|port| {
        let address = format!("127.0.0.1:{port}");
        Ok((Emulator::start(t, &["--cosim-tcp", &address])?, port))
    });
    let (emu, port) = match started {
        Ok(v) => v,
        Err(e) => {
            return Boot {
                boot: Err(e.clone()),
                cosim: Err(e.clone()),
                speed: Err(e),
            };
        }
    };
    let (mut clock, paused) = match lockstep(port) {
        Ok(v) => v,
        // The chip runs freely again once the socket closes.
        Err(e) => {
            return Boot {
                boot: emu
                    .wait_for(BOOT_MARKER, Duration::from_secs(20))
                    .map(|()| "Free-running boot succeeded".into()),
                cosim: Err(e),
                speed: Err("Cannot measure speed because cosim is not ready".into()),
            };
        }
    };
    let boot = boot_under_clock(&emu, &mut clock);
    let speed = match &boot {
        Ok(_) => speed(&mut clock),
        Err(_) => Err("Cannot measure speed because firmware did not boot".into()),
    };
    Boot {
        boot,
        cosim: Ok(paused),
        speed,
    }
}

/// Check that time stops without grants and follows one grant.
fn lockstep(port: u16) -> Result<(Clock, String)> {
    let (mut clock, start) =
        Clock::claim(port, Duration::from_secs(10)).map_err(|e| e.to_string())?;
    sleep(Duration::from_millis(300));
    let now = clock.advance(QUANTUM_NS).map_err(|e| e.to_string())?;
    let moved = now.saturating_sub(start);
    // The protocol allows an instruction and a 62.5 ns timer step.
    if moved.abs_diff(QUANTUM_NS) > 1_000 {
        return Err(format!("Granted 1 ms, advanced {moved} ns"));
    }
    Ok((
        clock,
        format!("Pause verified. Granted 1 ms, advanced {moved} ns"),
    ))
}

fn boot_under_clock(emu: &Emulator, clock: &mut Clock) -> Result<String> {
    let end = Instant::now() + Duration::from_secs(30);
    while Instant::now() < end {
        if emu.text().contains(BOOT_MARKER) {
            return Ok("Boot under held clock succeeded".into());
        }
        clock.advance(QUANTUM_NS).map_err(|e| e.to_string())?;
    }
    Err(emu.missing(BOOT_MARKER))
}

fn speed(clock: &mut Clock) -> Result<f64> {
    let begin = Instant::now();
    let mut quanta = 0;
    while quanta < 2000 && begin.elapsed() < Duration::from_secs(10) {
        clock.advance(QUANTUM_NS).map_err(|e| e.to_string())?;
        quanta += 1;
    }
    Ok(quanta as f64 / 1000.0 / begin.elapsed().as_secs_f64())
}

/// Send one message from the firmware through a temporary broker and back.
pub fn firmware_mqtt(t: &Toolchain) -> Result {
    let (_broker, port) = broker(t)?;
    let inject = format!("{port}\\n");
    let emu = Emulator::start(t, &["--inject-on", BOOT_MARKER, "--inject", &inject])?;
    emu.wait_for(MQTT_MARKER, Duration::from_secs(45))
}
